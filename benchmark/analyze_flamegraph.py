"""
Analyze HTML flamegraph generated by jfr-converter to extract top CPU consumer methods.
"""

import re
import sys
from pathlib import Path

def analyze(html_path: Path):
    if not html_path.exists():
        print(f"File {html_path} not found.")
        return

    content = html_path.read_text(encoding="utf-8")
    
    idx1 = content.find("const cpool = [")
    idx2 = content.find("];", idx1)
    if idx1 == -1 or idx2 == -1:
        print("cpool not found in flamegraph.")
        return

    cpool_lines = content[idx1:idx2].splitlines()[1:]
    frames = [line.strip().strip("',") for line in cpool_lines if line.strip()]
    
    print(f"Total Unique Methods in Flame Graph: {len(frames)}")
    
    # Filter Minecraft methods
    mc_frames = [f for f in frames if "minecraft" in f.lower() or "mojang" in f.lower()]
    print(f"\nTop Minecraft / Mojang frames ({len(mc_frames)} total):")
    for f in mc_frames[:25]:
        print(f"  - {f}")

if __name__ == "__main__":
    p = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("D:/apex-vanilla/run/test.html")
    analyze(p)
